import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const names = [
  'ac-portable', 'ac-split',
  'airflow-gentle', 'airflow-still', 'airflow-strong',
  'brand-snowflake', 'info', 'nav-home', 'nav-library', 'nav-saved', 'person',
  'priority-balanced', 'priority-cost', 'priority-energy',
  'roof-ceiling', 'roof-concrete', 'roof-floor', 'roof-none',
  'room-bedroom', 'room-living', 'room-office',
  'sun-high', 'sun-low', 'sun-medium',
  'window-large', 'window-none', 'window-small',
];

const lines = [
  '// Generated from assets/icons-modern/*.svg by node scripts/generate-icon-xml.mjs.',
  '// Edit the SVG sources, then rerun the generator. Do not edit this file by hand.',
  'export const iconXml = {',
];

for (const name of names) {
  const svg = readFileSync(join(projectRoot, 'assets', 'icons-modern', `${name}.svg`), 'utf8').trim();
  if (!svg.startsWith('<svg ') || !svg.endsWith('</svg>')) {
    throw new Error(`Invalid SVG source: ${name}`);
  }
  lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`);
}

lines.push('} as const;', '');
writeFileSync(join(projectRoot, 'src', 'data', 'iconXml.ts'), lines.join('\n'));
